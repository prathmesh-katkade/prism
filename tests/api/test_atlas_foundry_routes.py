def test_starting_a_foundry_job_against_a_real_dataset_version_queues_or_fails_honestly_without_soup() -> None:
    client = TestClient(create_app())
    _completed_train_split_run(client)
    built = client.post("/api/v1/atlas/foundry/training-datasets")
    assert built.status_code == 201
    assert built.json()["train_count"] >= 1
    version_id = built.json()["version_id"]

    recipe = {
        "recipe_id": "recipe_test_2",
        "base_model": "TinyLlama/TinyLlama-1.1B-Chat-v1.0",
        "method": AtlasTrainingRecipeMethod.QLORA.value,
        "task": "sft",
        "dataset_version_id": version_id,
        "created_at": "2026-01-01T00:00:00Z",
    }
    response = client.post(
        "/api/v1/atlas/foundry/jobs",
        params={"dataset_version_id": version_id},
        json=recipe,
    )
    assert response.status_code == 202
    job = response.json()
    # No `soup` binary in this environment: the job must fail honestly, not
    # pretend to train (unless capacity queued it first, also a valid state).
    assert job["state"] in {"failed", "queued"}

    fetched = client.get(f"/api/v1/atlas/foundry/jobs/{job['job_id']}")
    assert fetched.status_code == 200
    assert fetched.json()["job_id"] == job["job_id"]

    missing = client.get("/api/v1/atlas/foundry/jobs/does_not_exist")
    assert missing.status_code == 404


