def test_training_dataset_build_and_preview_round_trip_through_the_api() -> None:
    client = TestClient(create_app())
    _completed_run(client)  # ensures at least one eligible run exists in the shared store

    built = client.post("/api/v1/atlas/foundry/training-datasets")
    assert built.status_code == 201
    manifest = built.json()
    assert manifest["train_count"] + manifest["validation_count"] + manifest["test_count"] >= 1

    listed = client.get("/api/v1/atlas/foundry/training-datasets")
    assert listed.status_code == 200
    assert any(item["version_id"] == manifest["version_id"] for item in listed.json())

    preview = client.get(f"/api/v1/atlas/foundry/training-datasets/{manifest['version_id']}/preview")
    assert preview.status_code == 200
    assert len(preview.json()) >= 1


