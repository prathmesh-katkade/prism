def _dataset(client: TestClient) -> str:
    response = client.post(
        "/api/v1/overview/datasets",
        files={"file": ("unknown.csv", b"segment,revenue\na,10\nb,12\na,8\n", "text/csv")},
    )
    assert response.status_code == 201
    return str(response.json()["dataset_id"])


def _terminal_run(client: TestClient, run_id: str) -> AtlasRunResponse:
    for _ in range(100):
        response = client.get(f"/api/v1/atlas/runs/{run_id}")
        assert response.status_code == 200
        run = AtlasRunResponse.model_validate(response.json())
        if run.plan.state in {AtlasPlanState.COMPLETED, AtlasPlanState.FAILED, AtlasPlanState.CANCELLED}:
            return run
        time.sleep(0.01)
    raise AssertionError("Atlas run did not reach a terminal state")


def _completed_run(client: TestClient, *, objective: str = "Understand this dataset safely.") -> AtlasRunResponse:
    dataset_id = _dataset(client)
    started = client.post("/api/v1/atlas/runs", json={"dataset_id": dataset_id, "objective": objective})
    assert started.status_code == 202
    run = _terminal_run(client, started.json()["run_id"])
    assert run.plan.state is AtlasPlanState.COMPLETED
    return run


def _completed_train_split_run(client: TestClient) -> AtlasRunResponse:
    """Create genuine, distinct durable runs until the deterministic split is TRAIN.

    Dataset identifiers are intentionally generated by DatasetStore, so a
    single real run can legitimately hash into validation or test. This helper
    retains the production split policy and makes the route test exercise the
    actual TRAIN-only export path rather than weakening it.
    """
    for attempt in range(12):
        run = _completed_run(client, objective=f"Understand verified training fixture {attempt} safely.")
        if _assign_split(run.plan.dataset_id) is AtlasTrainingSplit.TRAIN:
            return run
    raise AssertionError("Could not create a deterministic TRAIN-split Atlas fixture after 12 attempts")


